// Firma de release: se lee de keystore.properties, que NO se versiona.
// Sin ese archivo el proyecto compila igual, pero el release sale sin firmar.
// Ver docs/RELEASE.md.
val keystorePropertiesFile = rootProject.file("keystore.properties")
val keystoreProperties = Properties().apply {
    if (keystorePropertiesFile.exists()) {
        keystorePropertiesFile.inputStream().use { load(it) }
    }
}

android {
    namespace = "com.example.crosswalker"
    compileSdk {
        version = release(37)
    }

    defaultConfig {
        applicationId = "com.crosswalker.game"
        minSdk = 24
        targetSdk = 37
        versionCode = 1
        versionName = "1.0"

        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }

    signingConfigs {
        if (keystorePropertiesFile.exists()) {
            create("release") {
                storeFile = rootProject.file(keystoreProperties.getProperty("storeFile"))
                storePassword = keystoreProperties.getProperty("storePassword")
                keyAlias = keystoreProperties.getProperty("keyAlias")
                keyPassword = keystoreProperties.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            optimization {
                enable = true
            }
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro"
            )
            signingConfig = signingConfigs.findByName("release")
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_11
        targetCompatibility = JavaVersion.VERSION_11
    }
    buildFeatures {
        compose = true
    }
    sourceSets {
        getByName("main") {
            res.directories.clear()
            res.directories.add(rootProject.file("assets/game/res").absolutePath)
            assets.directories.clear()
            assets.directories.add(rootProject.file("assets/game/files").absolutePath)
        }
        getByName("test") {
            resources.directories.add(rootProject.file("assets/game/files").absolutePath)
        }
    }
}

